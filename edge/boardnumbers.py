"""Write the LaTeX macros of the on-board results (Section V-E) from the aggregates of protocol P29, the same way
experiments/pb/texnumbers.py writes those of the server: nothing is typed by hand.

    python3 boardnumbers.py --board docs/results/board_p29 --main docs/results/frozen_v6/main_v6.json --out numbers_board.tex

Reads summary.json, mm_summary_*.json and cmp_*.json of the board runs, and costfig/cost_*.dat written on the board by
p29_costfig.py (fit of the cost model and its errors). A run that has not happened yet leaves its macros out.
"""
import argparse
import json
import os
from decimal import Decimal, ROUND_HALF_UP


def sep(x):
    """An integer, rounded half up like the reports, with the thousands separator in braces (right in text and math)."""
    n = int(Decimal(str(x)).quantize(Decimal(1), rounding=ROUND_HALF_UP))
    return f"{n:,}".replace(",", "{,}")


def diff_text(d, lo, hi):
    """A difference with its 95% interval; a bound that would round to 0.0 keeps two decimals, as in texnumbers.py."""
    def bound(x):
        s = f"{x:+.1f}"
        return f"{x:+.2f}" if s in ("+0.0", "-0.0") and x != 0 else s
    return f"${d:+.1f}$ (${bound(lo)}$ to ${bound(hi)}$)"


def dat(path):
    """Rows of a whitespace table with a header line, as dicts of strings."""
    if not os.path.exists(path):
        return []
    lines = [l.split() for l in open(path) if l.strip()]
    return [dict(zip(lines[0], r)) for r in lines[1:]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", required=True)
    ap.add_argument("--main", required=True, help="frozen main table JSON (input lengths of the 2B whole-image rows)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--select", help="select_demo JSON (problem (12) on the validation images, docs/results/select_demo/)")
    a = ap.parse_args()
    B = a.board
    out = ["% Generated by experiments/edge/boardnumbers.py from docs/results/board_p29 (protocol P29) - do not edit."]

    def put(name, value, note):
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}  % {note}")

    def load(name):
        p = os.path.join(B, name)
        return json.load(open(p)) if os.path.exists(p) else None

    s = load("summary.json")
    for sc, suf in (("ed", "ED"), ("td", "TD")):
        put(f"bdDetMs{suf}", sep(s["detector"][sc]["whole image"]["median"]), "detector per image, median ms")
        put(f"bdComposeMs{suf}", f"{s['compose'][sc]['median']:.1f}", "list composition, median ms")
        lb = s["llm"]["llm_boardlists"][sc]
        put(f"bdListLmMs{suf}", sep(lb["wall_ms"]["median"]), "list only, language model per question, median ms (board lists)")
        put(f"bdListIn{suf}", sep(lb["input_tokens"]["median"]), "list only, input tokens, median")
        # 2026-10-29 (author's note N3): the sum of the stage medians, as for the thumbnail tier below, so that the column of
        # Table VII adds up; the median of the per-question totals (end_to_end) is 792 / 1,109 ms, not used.
        tot = s["detector"][sc]["whole image"]["median"] + s["compose"][sc]["median"] + lb["wall_ms"]["median"]
        put(f"bdListTotalMs{suf}", sep(tot), "list only, sum of the stage medians (detector + list + language model), ms")
        put(f"bdListTotalS{suf}", f"{tot / 1000:.2f}", "the same in s")
    put("bdListMemMB", sep(s["llm"]["llm_boardlists"]["all"]["memory_mb_max"]), "list only, largest memory reported by the runtime, MiB")
    put("bdCalibSec", sep(s["conditions"]["llm_lengths"]["seconds"]), "duration of the calibration sweep of the prefill (90 calls), s")

    # 2026-10-29: the thumbnail tier reran on the board's own candidates (mmboard, mmdarkboard); its rows, the paired
    # differences from the list-only tier and the stage times now come from those runs, so both tiers are all on the board
    pairs = [("List", "cmp_test_boardlists_float.json", "acc_boardlists", "clean, list only, all on the board"),
             ("Thumb", "cmp_mmall_boardlists_float.json", "acc_board", "clean, thumbnail tier, all on the board"),
             ("ListDark", "cmp_dark_board_float.json", "acc_board", "low light, list only, server lists"),
             ("ListBoardDark", "cmp_darkboard_board_float.json", "acc_board", "low light, list only, all on the board"),
             ("ThumbDark", "cmp_mmdark_boardlists_float.json", "acc_board", "low light, thumbnail tier, all on the board")]
    for name, f, key, note in pairs:
        c = load(f)
        if c is None:
            continue
        for sc, suf in (("ed", "ED"), ("td", "TD")):
            r = c["scenarios"][sc]
            put(f"bd{name}Acc{suf}", f"{r[key]:.1f}", f"{note}: board accuracy")
            put(f"bd{name}Float{suf}", f"{r['acc_float']:.1f}", f"{note}: server float accuracy on the same questions")
        r = c["scenarios"]["all"]
        put(f"bd{name}DiffAll", diff_text(r["diff"], *r["ci95"]), f"{note}: board minus float, both datasets")
        put(f"bd{name}Same", f"{r['same_correctness']:.1f}", f"{note}: share of questions answered alike (right or wrong), %")

    for name, f, note in (("Dark", "cmp_dark_thumbboard_vs_listonly.json", "low light"), ("Clean", "cmp_test_thumbboard_vs_listonly.json", "clean")):
        c = load(f)
        if c is None:
            continue
        for sc, suf in (("ed", "ED"), ("td", "TD"), ("all", "All")):
            r = c["scenarios"][sc]
            put(f"bd{name}ThumbVsList{suf}", diff_text(r["diff"], *r["ci95"]), f"{note}: thumbnail tier minus list only, on the board")
            put(f"bd{name}ThumbVsListPt{suf}", f"{abs(r['diff']):.1f}", f"{note}: |difference|")

    m = load("mm_summary_all_boardlists.json")
    for sc, suf in (("ed", "ED"), ("td", "TD")):
        r = m["scenarios"][sc]
        put(f"bdThumbVisMs{suf}", sep(r["vision_ms_median"]), "thumbnail tier, vision encoder per image, median ms")
        put(f"bdThumbLmMs{suf}", sep(r["llm_ms_median"]), "thumbnail tier, language model per question, median ms")
        put(f"bdThumbIn{suf}", sep(r["tokens_median"]), "thumbnail tier, input tokens, median")
        tot = s["detector"][sc]["whole image"]["median"] + r["vision_ms_median"] + r["llm_ms_median"]
        put(f"bdThumbTotalS{suf}", f"{tot / 1000:.1f}", "thumbnail tier, sum of the stage medians, s")
    put("bdThumbMemMB", sep(max(m["scenarios"][sc]["memory_mb_max"] for sc in ("ed", "td"))),
        "thumbnail tier, largest memory reported by the runtime (two vision encoders loaded), MiB")
    # 2026-10-29 (author's note N2): the thumbnail tier skips the ED images whose aspect ratio has no exported encoder
    put("bdThumbNAll", sep(m["n"]), "thumbnail tier: questions answered on the board")
    put("bdListNAll", sep(sum(s["llm"]["llm_boardlists"][sc]["wall_ms"]["n"] for sc in ("ed", "td"))), "list only: questions answered on the board")
    put("bdThumbSkipImgED", sep(s["detector"]["ed"]["whole image"]["n"] - m["scenarios"]["ed"]["images"]),
        "ED test images left out of the thumbnail tier (no vision encoder exported for their aspect ratio)")

    # cost model: coefficients, errors, predictions at the operating points. Since 2026-10-29 (author's note N7) from
    # costfig_boardlists (experiments/edge/p29_costfig_b.py): calibrated and checked on the runs that read the board's
    # own candidates, the runs of Table VII; costfig/ holds the earlier computation on the server-candidate runs
    CF = "costfig_boardlists"
    fit = dat(os.path.join(B, CF, "cost_fit.dat"))[0]
    b1, b2 = float(fit["beta1"]), float(fit["beta2"])
    t0l, t0t = float(fit["t0list"]), float(fit["t0thumb"])
    g1, g2 = float(fit["gamma1"]), float(fit["gamma2"])
    f = lambda L: b1 * L + b2 * L * L
    put("bdBetaOne", f"{b1:.2f}", "beta_1, ms per token")
    put("bdBetaTwo", f"{b2 * 1e4:.2f}", "beta_2 in 1e-4 ms per token^2")
    put("bdTzeroList", sep(t0l), "t_0 without the thumbnail, ms")
    put("bdTzeroThumb", sep(t0t), "t_0 with the thumbnail, ms")
    put("bdGammaOne", f"{g1:.2f}", "gamma_1, ms per token")
    put("bdGammaTwo", f"{g2:.4f}", "gamma_2, ms per token^2")
    for k, v in (("bdBetaOneRaw", b1), ("bdBetaTwoRaw", b2), ("bdTzeroListRaw", t0l), ("bdTzeroThumbRaw", t0t),
                 ("bdGammaOneRaw", g1), ("bdGammaTwoRaw", g2)):
        put(k, f"{v:.6g}", "unrounded, for the curves of the figure")
    for r in dat(os.path.join(B, CF, "cost_refit.dat"))[:1]:
        put("bdRefitOneRaw", f"{float(r['beta1']):.6g}", "beta_1 calibrated over 64-2,000 tokens, unrounded, for the figure")
        put("bdRefitTwoRaw", f"{float(r['beta2']):.6g}", "beta_2 calibrated over 64-2,000 tokens, unrounded, for the figure")
    err = {r["set"]: r for r in dat(os.path.join(B, CF, "cost_err.dat"))}
    names = {"fitprefill": "FitPrefill", "fitvision": "FitVision", "list": "List", "thumb": "Thumb", "thumbdark": "ThumbDark",
             "listdark": "ListDark", "listboarddark": "ListBoardDark", "listboard": "ListBoard", "longlen": "Long",
             "refitall": "Refit"}
    for k, r in err.items():
        if k in ("fitprefill", "fitvision", "refitall"):
            what, high = f"largest relative error of the fit, % ({r['n']} lengths or sizes)", None
        elif k == "longlen":
            what, high = f"smallest gap of the median above the curve, % ({r['n']} lengths)", "largest gap, %"
        else:
            what, high = f"median relative error of the prediction, % ({r['n']} calls)", "95th percentile, %"
        put(f"bdErr{names[k]}", f"{float(r['medrel']):.1f}", f"{k}: {what}")
        if r["p95rel"] != "nan":
            put(f"bdErr{names[k]}High", f"{float(r['p95rel']):.1f}", f"{k}: {high}")
        put(f"bdErrN{names[k]}", sep(int(r["n"])), f"{k}: number of calls, lengths or sizes")
    for mf in dat(os.path.join(B, CF, "cost_mem_fit.dat"))[:1]:
        put("bdMemSlope", f"{float(mf['slope_mb_per_token']):.2f}", "memory per input token, MiB")
        put("bdMemSlopeRaw", mf["slope_mb_per_token"], "the same, unrounded, for the figure")
        put("bdMemBaseRaw", mf["base_mb"], "memory at zero input tokens, MiB, unrounded, for the figure")
        put("bdMemBase", sep(float(mf["base_mb"])), "memory at zero input tokens, MiB (max_context_len 1,024)")
    main = json.load(open(a.main))
    for sc, suf in (("ed", "ED"), ("td", "TD")):
        lb = s["llm"]["llm_boardlists"][sc]["input_tokens"]["median"]
        put(f"bdListLmPredMs{suf}", sep(f(lb) + t0l), "list only, predicted language model time at the median input, ms")
        lt = m["scenarios"][sc]["tokens_median"]
        put(f"bdThumbLmPredMs{suf}", sep(f(lt) + t0t), "thumbnail tier, predicted language model time at the median input, ms")
        vis = {int(r["n"]): float(r["ms"]) for r in dat(os.path.join(B, CF, "cost_vision.dat"))}
        n_whole = main[f"{sc}/整图 576 令牌（2B）"]["visual_tokens"]
        L_whole = main[f"{sc}/整图 576 令牌（2B）"]["input_tokens"]
        put(f"bdWholeVisMs{suf}", sep(vis[int(round(n_whole))]), "whole image, 576 tokens: vision encoder measured on the board, ms")
        put(f"bdWholeLmPredMs{suf}", sep(f(L_whole) + t0t), "whole image, 576 tokens: language model predicted, ms")
        put(f"bdWholeTotalS{suf}", f"{(vis[int(round(n_whole))] + f(L_whole) + t0t) / 1000:.1f}", "whole image, 576 tokens: encoder + language model, s")
        L_nat = main[f"{sc}/整图原始分辨率（2B）"]["input_tokens"]
        put(f"bdNativePrefillS{suf}", f"{f(L_nat) / 1000:.0f}", "native resolution: predicted prefill alone, s (beyond the context of the export)")
    lng = dat(os.path.join(B, CF, "cost_longlen.dat"))
    if lng:
        gaps = [(float(r["ms"]) - float(r["curve"])) / float(r["ms"]) * 100 for r in lng]
        put("bdLongLow", f"{min(gaps):.1f}", "measured median above the curve fitted below 896 tokens, smallest gap, % of measured")
        put("bdLongHigh", f"{max(gaps):.1f}", "the same, largest gap, %")
        put("bdLongMax", sep(max(int(r["L"]) for r in lng)), "longest input of the extrapolation check")
    mc = dat(os.path.join(B, CF, "cost_memctx.dat"))
    if len(mc) >= 2:
        xs = [int(r["Lmax"]) for r in mc]
        ys = [float(r["MBshort"]) for r in mc]
        slope = (ys[-1] - ys[0]) / (xs[-1] - xs[0])
        put("bdKvPerToken", f"{slope * 1024:.0f}", "memory per reserved context token, KiB (from max_context_len 512 to 2,048)")
        put("bdKvSlopeRaw", f"{slope:.6g}", "the same in MiB, unrounded, for the figure")
        put("bdKvStartRaw", f"{ys[0]:.1f}", f"memory at max_context_len {xs[0]} (64-token input), MiB, for the figure")
    # 2026-10-29: medium detector over all test images (tools/board_detm_all.sh) and the tier selection of III-F
    dm = load("detm_all_summary.json")
    if dm:
        for sc, suf in (("ed", "ED"), ("td", "TD")):
            put(f"bdDetMedMs{suf}", sep(dm[f"{sc}/medium"]["whole_median_ms"]), "medium detector per image, median ms over all test images")
    if a.select:
        sel = json.load(open(a.select))
        rows = {"NanoList": "Tier 0，纳米，只读清单", "MedList": "Tier 0，中型，只读清单", "NanoThumbSmall": "Tier 1，纳米，196 令牌",
                "NanoThumbMid": "Tier 1，纳米，256 令牌"}
        for key, name in rows.items():
            for sc, suf in (("ed", "ED"), ("td", "TD")):
                r = sel[name][sc]
                put(f"sel{key}S{suf}", f"{r['clean']['T_median'] / 1000:.2f}", f"{name}: predicted time per question by (10), clean, median, s")
                put(f"sel{key}Nine{suf}", f"{r['expected']['0.9']:.1f}", f"{name}: expected accuracy, nine clean in ten, validation, %")
                put(f"sel{key}Half{suf}", f"{r['expected']['0.5']:.1f}", f"{name}: expected accuracy, half in low light, validation, %")
                put(f"sel{key}Dark{suf}", f"{r['dark2']['acc']:.1f}", f"{name}: accuracy in low light (dark, strength 2), validation, %")
    with open(a.out, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(a.out, sum(1 for l in out if l.startswith("\\")), "macros")


if __name__ == "__main__":
    main()
